import { chromium, _electron } from 'playwright-core';
import { startHarness } from '../test/helpers/server.ts';
import { randomBytes } from 'node:crypto';
import { mkdtempSync, rmSync, readFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
delete process.env.ELECTRON_RUN_AS_NODE;
const root=fileURLToPath(new URL('..', import.meta.url));
const artifact=process.env.WORKMATES_PROOF_DIR || mkdtempSync(join(tmpdir(),'workmates-client-proof-')); mkdirSync(artifact,{recursive:true});
const data=mkdtempSync(join(tmpdir(),'wm-both-data-'));
const profile=mkdtempSync(join(tmpdir(),'wm-both-desktop-'));
const token=randomBytes(32).toString('hex');
const server=await startHarness({WORKMATES_HOSTED:'1',WORKMATES_SERVER_TOKEN:token,WORKMATES_DATA_DIR:data,WORKMATES_STATIC_DIR:root+'/dist',WORKMATES_PUBLIC_URL:''});
let browser, electron;
try {
 const auth={authorization:`Bearer ${token}`,'content-type':'application/json'};
 await fetch(server.url+'/api/config',{method:'PUT',headers:auth,body:JSON.stringify({setupDone:true})});
 const created=await fetch(server.url+'/api/bots',{method:'POST',headers:auth,body:JSON.stringify({name:'Shared proof agent',title:'Works across devices'})}).then(r=>r.json());
 browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH || undefined,args:['--no-sandbox']});
 const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 const page=await context.newPage(); const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto(server.url); await page.getByRole('heading',{name:'Your workspace, anywhere'}).waitFor();
 await page.getByLabel('Server access key').fill('incorrect'); await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await page.getByRole('alert').filter({hasText:'incorrect'}).waitFor();
 await page.getByLabel('Server access key').fill(token); await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await page.getByText('Shared proof agent',{exact:true}).first().waitFor();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 assert.equal(await page.evaluate(()=>document.cookie.includes('workmates_session')),false);
 await page.reload(); await page.getByText('Shared proof agent',{exact:true}).first().waitFor();
 await page.evaluate(()=>navigator.serviceWorker.ready);
 const cdp=await context.newCDPSession(page); const manifest=await cdp.send('Page.getAppManifest'); assert.equal(manifest.errors.length,0);
 const installability=await cdp.send('Page.getInstallabilityErrors'); assert.deepEqual(installability.installabilityErrors,[]);
 await page.screenshot({path:artifact+'/mobile.png'});
 const uploadedResponse=page.waitForResponse(r=>r.url().endsWith('/api/attachments/file') && r.request().method()==='POST');
 await page.locator('input[type=file]').setInputFiles({name:'phone-notes.txt',mimeType:'text/plain',buffer:Buffer.from('Mobile picker upload')});
 const uploaded=await (await uploadedResponse).json();
 assert.equal(readFileSync(uploaded.path,'utf8'),'Mobile picker upload');
 await page.getByText('phone-notes.txt',{exact:true}).waitFor();
 console.log('Mobile sign-in, rejected key, reload, viewport, file picker upload and PWA manifest passed');
 electron=await _electron.launch({executablePath:process.env.WORKMATES_ELECTRON_PATH || root+'/node_modules/electron/dist/electron',args:process.env.WORKMATES_ELECTRON_PATH ? ['--no-sandbox'] : ['--no-sandbox',root],env:{...process.env,WORKMATES_DESKTOP_USER_DATA:profile,WORKMATES_DESKTOP_STATIC_DIR:root+'/dist',WORKMATES_SERVER_URL:server.url,WORKMATES_SERVER_TOKEN:''},timeout:30000});
 const desktop=await electron.firstWindow(); await desktop.getByLabel('Server access key').fill(token); await desktop.getByRole('button',{name:'Connect workspace'}).click();
 await desktop.getByText('Shared proof agent',{exact:true}).first().waitFor();
 assert.equal((await desktop.evaluate(()=>window.rooms.serverConnection())).mode,'remote');
 assert.equal(readFileSync(join(profile,'server-connection.json'),'utf8').includes(token),false);
 await desktop.evaluate(async (id)=>{await fetch('/api/bots/'+id,{method:'PATCH',headers:{'content-type':'application/json'},body:JSON.stringify({name:'Changed on desktop'})});},created.bot.id);
 await page.getByText('Changed on desktop',{exact:true}).first().waitFor();
 await desktop.screenshot({path:artifact+'/desktop.png'});
 for (const width of [320,768,1440,390]) {
   await page.setViewportSize({width,height:844});
   assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 }
 console.log('Actual Electron connection, live mobile synchronization and four responsive widths passed');
 await page.getByTitle('Settings',{exact:true}).click();
 await page.getByRole('button',{name:'Sign out of this device'}).waitFor();
 await page.screenshot({path:artifact+'/mobile-settings.png'});
 await page.getByRole('button',{name:'Sign out of this device'}).click();
 await page.getByRole('heading',{name:'Your workspace, anywhere'}).waitFor();
 assert.equal(await desktop.evaluate(()=>fetch('/api/bots').then(r=>r.status)),200);
 await context.setOffline(true); await page.reload(); await page.getByRole('heading',{name:'Reconnect to your workspace'}).waitFor();
 await context.setOffline(false); await page.getByRole('link',{name:'Try again'}).click(); await page.getByRole('heading',{name:'Your workspace, anywhere'}).waitFor();
 assert.deepEqual(errors,[]);
 console.log('Mobile sign-out, desktop independence, offline fallback and recovery passed');
} finally { if(electron) await electron.close(); if(browser) await browser.close(); await server.stop(); rmSync(data,{recursive:true,force:true}); rmSync(profile,{recursive:true,force:true}); }
